/// <reference types="tree-sitter-cli/dsl" />
// @ts-check

const PREC = {
  assignment: 1,
  lambda: 2,
  logicalOr: 3,
  logicalAnd: 4,
  comparison: 5,
  bitwiseOr: 6,
  bitwiseXor: 7,
  bitwiseAnd: 8,
  shift: 9,
  pipe: 10,
  range: 11,
  add: 12,
  multiply: 13,
  unary: 14,
  postfix: 15,
};

module.exports = grammar({
  name: "olang",

  extras: ($) => [/[\s\uFEFF\u2060\u200B]/, $.comment],
  word: ($) => $.identifier,

  conflicts: ($) => [
    [$.block, $.object],
    [$.tuple, $.parenthesized_expression],
    [$.struct_pattern, $.struct_literal],
    [$.function_type, $.tuple_type],
    [$.union_type, $.function_type],
    [$.intersection_type, $.function_type],
    [$.tuple_type],
    [$.enum_variant, $.object_type],
    [$.parameter, $._primary_expression],
    [$._primary_expression, $.struct_literal],
    [$._pattern, $.struct_pattern],
    [$._pattern, $.enum_pattern],
  ],

  rules: {
    source_file: ($) => repeat($._statement),

    _statement: ($) => choice(
      $.share_declaration,
      $.use_declaration,
      $.test_declaration,
      $.error_declaration,
      $.type_declaration,
      $.trait_declaration,
      $.impl_declaration,
      $.function_declaration,
      $.let_declaration,
      $.expression_statement,
    ),

    expression_statement: ($) => seq($._expression, optional(";")),

    share_declaration: ($) => seq(
      "share",
      choice(
        $.use_declaration,
        $.function_declaration,
        $.let_declaration,
        $.type_declaration,
        $.trait_declaration,
        $.impl_declaration,
      ),
    ),

    use_declaration: ($) => prec.right(seq(
      "use",
      field("path", $.use_path),
      optional(seq("{", optional(commaSep1(choice($.identifier, "*"))), optional(","), "}")),
      optional(";"),
    )),
    use_path: ($) => seq($.identifier, repeat(seq(".", $.identifier))),

    test_declaration: ($) => seq("test", field("name", $.string), field("body", $.block)),

    error_declaration: ($) => seq(
      "error",
      field("name", $.type_identifier),
      "{",
      optional(commaSep1($.enum_variant)),
      optional(","),
      "}",
    ),

    type_declaration: ($) => seq(
      "type",
      field("name", $.type_identifier),
      optional($.type_parameters),
      "=",
      field("value", $._type),
      optional(";"),
    ),

    struct_type: ($) => seq("struct", "{", optional(commaSep1($.field_declaration)), optional(","), "}"),
    enum_type: ($) => seq("enum", "{", optional(commaSep1($.enum_variant)), optional(","), "}"),
    enum_variant: ($) => seq(
      field("name", $.type_identifier),
      optional(choice(
        seq("(", optional(commaSep1($._type)), ")"),
        seq("{", optional(commaSep1($.field_declaration)), optional(","), "}"),
        seq(":", choice($._type, seq("{", optional(commaSep1($.field_declaration)), optional(","), "}"))),
      )),
    ),
    field_declaration: ($) => seq(field("name", $.identifier), ":", field("type", $._type)),

    trait_declaration: ($) => seq(
      "trait",
      field("name", $.type_identifier),
      "{",
      repeat($.trait_method),
      "}",
    ),
    trait_method: ($) => seq(
      "fn",
      field("name", $.identifier),
      field("parameters", $.parameters),
      optional(seq("->", field("return_type", $._type))),
      optional(seq("=", field("body", $._expression))),
      optional(";"),
    ),
    impl_declaration: ($) => seq(
      "impl",
      field("trait", $.type_identifier),
      "for",
      field("type", $.type_identifier),
      "{",
      repeat($.function_declaration),
      "}",
    ),

    function_declaration: ($) => seq(
      optional("async"),
      "fn",
      field("name", $.identifier),
      optional($.type_parameters),
      field("parameters", $.parameters),
      optional(seq("->", field("return_type", $._type))),
      "=",
      field("body", $._expression),
      optional(";"),
    ),
    parameters: ($) => seq("(", optional(commaSep1($.parameter)), optional(","), ")"),
    parameter: ($) => seq(
      field("name", $.identifier),
      optional(seq(":", field("type", $._type))),
      optional(seq("=", field("default", $._expression))),
    ),
    type_parameters: ($) => seq("<", commaSep1($.type_parameter), ">"),
    type_parameter: ($) => seq($.type_identifier, optional(seq(":", $.type_identifier, repeat(seq("+", $.type_identifier))))),

    let_declaration: ($) => prec.right(seq(
      "let",
      optional("mut"),
      field("pattern", $._pattern),
      optional(seq(":", field("type", $._type))),
      optional(seq("=", field("value", $._expression))),
      optional(";"),
    )),

    _expression: ($) => choice(
      $.assignment_expression,
      $.lambda_expression,
      $.if_expression,
      $.match_expression,
      $.try_expression,
      $.for_expression,
      $.while_expression,
      $.loop_expression,
      $.break_expression,
      $.continue_expression,
      $.return_expression,
      $.spawn_expression,
      $.await_expression,
      $.binary_expression,
      $.unary_expression,
      $._postfix_expression,
    ),

    assignment_expression: ($) => prec.right(PREC.assignment, seq(
      field("left", choice($.identifier, $.member_expression, $.index_expression)),
      "=",
      field("right", $._expression),
    )),
    lambda_expression: ($) => prec.right(PREC.lambda, seq(
      optional("async"),
      field("parameters", $.parameters),
      optional(seq("->", field("return_type", $._type))),
      "=>",
      field("body", $._expression),
    )),

    if_expression: ($) => prec.right(seq(
      "if",
      field("condition", $._expression),
      "=>",
      field("consequence", $._expression),
      optional(seq("else", optional("=>"), field("alternative", $._expression))),
    )),
    match_expression: ($) => seq("match", field("value", $._expression), "{", repeat1($.match_arm), "}"),
    match_arm: ($) => seq(
      field("pattern", $._pattern),
      optional(seq("if", field("guard", $._expression))),
      "=>",
      field("value", $._expression),
      optional(","),
    ),
    try_expression: ($) => seq("try", field("body", $.block), "catch", "(", field("error", $.identifier), ")", field("handler", $.block)),
    for_expression: ($) => seq("for", field("pattern", choice($.identifier, $.tuple_pattern)), "in", field("iterator", $._expression), field("body", $.block)),
    while_expression: ($) => seq("while", field("condition", $._expression), field("body", $.block)),
    loop_expression: ($) => seq("loop", field("body", $.block)),
    break_expression: ($) => prec.right(seq("break", optional($._expression))),
    continue_expression: () => "continue",
    return_expression: ($) => prec.right(seq("return", optional($._expression))),
    spawn_expression: ($) => prec.right(seq("spawn", $._expression)),
    await_expression: ($) => prec.right(seq("await", $._expression)),

    binary_expression: ($) => choice(
      binary($, PREC.logicalOr, "||"),
      binary($, PREC.logicalAnd, "&&"),
      binary($, PREC.comparison, choice("==", "!=", "<", "<=", ">", ">=")),
      binary($, PREC.bitwiseOr, "|"),
      binary($, PREC.bitwiseXor, "^"),
      binary($, PREC.bitwiseAnd, "&"),
      binary($, PREC.shift, choice("<<", ">>")),
      binary($, PREC.pipe, "|>"),
      binary($, PREC.range, choice("..", "..=")),
      binary($, PREC.add, choice("+", "-")),
      binary($, PREC.multiply, choice("*", "/", "%")),
    ),
    unary_expression: ($) => prec.right(PREC.unary, seq(field("operator", choice("!", "-")), field("operand", $._expression))),

    _postfix_expression: ($) => choice(
      $._primary_expression,
      $.call_expression,
      $.member_expression,
      $.index_expression,
      $.try_postfix_expression,
    ),
    call_expression: ($) => prec.left(PREC.postfix, seq(field("function", $._postfix_expression), field("arguments", $.arguments))),
    member_expression: ($) => prec.left(PREC.postfix, seq(field("object", $._postfix_expression), ".", field("property", $.identifier))),
    index_expression: ($) => prec.left(PREC.postfix, seq(field("object", $._postfix_expression), "[", field("index", $._expression), "]")),
    try_postfix_expression: ($) => prec.left(PREC.postfix, seq(field("value", $._postfix_expression), "?")),
    arguments: ($) => seq("(", optional(commaSep1($.argument)), optional(","), ")"),
    argument: ($) => choice($.named_argument, $._expression),
    named_argument: ($) => seq(field("name", $.identifier), ":", field("value", $._expression)),

    _primary_expression: ($) => choice(
      $.identifier,
      $.integer,
      $.float,
      $.string,
      $.raw_string,
      $.template_string,
      $.character,
      $.boolean,
      $.list,
      $.tuple,
      $.map,
      $.struct_literal,
      $.object,
      $.block,
      $.parenthesized_expression,
    ),
    parenthesized_expression: ($) => seq("(", $._expression, ")"),
    list: ($) => seq("[", optional(commaSep1($._expression)), optional(","), "]"),
    tuple: ($) => seq("(", $._expression, ",", commaSep1($._expression), optional(","), ")"),
    map: ($) => seq("#{", optional(commaSep1($.map_entry)), optional(","), "}"),
    map_entry: ($) => seq(field("key", $._expression), ":", field("value", $._expression)),
    object: ($) => seq("{", optional(commaSep1($.field_initializer)), optional(","), "}"),
    struct_literal: ($) => seq(field("type", $.identifier), "{", optional(commaSep1($.field_initializer)), optional(","), "}"),
    field_initializer: ($) => seq(field("name", $.identifier), ":", field("value", $._expression)),
    block: ($) => seq("{", repeat($._statement), "}"),

    _pattern: ($) => choice(
      $.or_pattern,
      $.range_pattern,
      $.result_pattern,
      $.struct_pattern,
      $.list_pattern,
      $.tuple_pattern,
      $.enum_pattern,
      $.rest_pattern,
      $.wildcard_pattern,
      $.identifier,
      $.integer,
      $.string,
      $.character,
      $.boolean,
    ),
    or_pattern: ($) => prec.left(seq($._pattern, "|", $._pattern)),
    range_pattern: ($) => seq(choice($.integer, $.character), choice("..", "..="), choice($.integer, $.character)),
    result_pattern: ($) => seq(field("variant", choice("Ok", "Err")), "(", $._pattern, ")"),
    enum_pattern: ($) => seq(field("variant", $.identifier), "(", commaSep1($._pattern), ")"),
    struct_pattern: ($) => seq(field("type", optional($.identifier)), "{", optional(commaSep1($.pattern_field)), optional(","), "}"),
    pattern_field: ($) => seq($.identifier, optional(seq(":", $._pattern))),
    list_pattern: ($) => seq("[", optional(commaSep1($._pattern)), optional(","), "]"),
    tuple_pattern: ($) => seq("(", $._pattern, ",", commaSep1($._pattern), optional(","), ")"),
    rest_pattern: ($) => seq("...", $.identifier),
    wildcard_pattern: () => "_",

    _type: ($) => choice(
      $.struct_type,
      $.enum_type,
      $.union_type,
      $.intersection_type,
      $.function_type,
      $.generic_type,
      $.list_type,
      $.tuple_type,
      $.object_type,
      $.unit_type,
      $.builtin_type,
      $.type_identifier,
      $.string,
      $.integer,
      $.boolean,
    ),
    union_type: ($) => prec.left(seq($._type, "|", $._type)),
    intersection_type: ($) => prec.left(seq($._type, "&", $._type)),
    function_type: ($) => seq("(", optional(commaSep1($._type)), ")", "->", $._type),
    generic_type: ($) => seq($.type_identifier, "<", commaSep1($._type), ">"),
    list_type: ($) => seq("[", $._type, "]"),
    tuple_type: ($) => seq("(", $._type, ",", commaSep1($._type), ")"),
    object_type: ($) => seq("{", optional(commaSep1($.field_declaration)), optional(","), "}"),
    unit_type: () => "()",
    builtin_type: () => choice("Int", "Float", "String", "Bool", "Map", "List", "Tuple", "Result", "Promise"),

    boolean: () => choice("true", "false"),
    integer: () => token(choice(
      /[+-]?0[bB][01](?:_?[01])*/,
      /[+-]?0[oO][0-7](?:_?[0-7])*/,
      /[+-]?0[xX][0-9a-fA-F](?:_?[0-9a-fA-F])*/,
      /[+-]?[0-9](?:_?[0-9])*/,
    )),
    float: () => token(/[+-]?[0-9](?:_?[0-9])*\.[0-9](?:_?[0-9])*(?:[eE][+-]?[0-9](?:_?[0-9])*)?/),
    string: () => token(seq('"', repeat(choice(/[^"\\]/, /\\./)), '"')),
    raw_string: () => token(seq('r"', repeat(choice(/[^"\\]/, /\\./)), '"')),
    template_string: () => token(seq("`", repeat(choice(/[^`\\]/, /\\./)), "`")),
    character: () => token(seq("'", choice(/[^'\\\n]/, /\\./), "'")),
    identifier: () => /[A-Za-z][A-Za-z0-9_]*/,
    type_identifier: () => /[A-Z][A-Za-z0-9_]*/,
    comment: () => token(seq("//", /[^\r\n]*/)),
  },
});

function commaSep1(rule) {
  return seq(rule, repeat(seq(",", rule)));
}

function binary($, precedence, operator) {
  return prec.left(precedence, seq(
    field("left", $._expression),
    field("operator", operator),
    field("right", $._expression),
  ));
}
